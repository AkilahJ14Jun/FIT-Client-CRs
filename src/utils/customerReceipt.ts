export function openWhatsAppWeb(payload: WhatsAppPayload): void {
  window.open(payload.waMe, '_blank');
}

/**
 * ★ CR FIX — triggerWhatsAppAutomation ★
 *
 * BEFORE (buggy):
 *   - Called downloadReceiptAsPDF() ✓
 *   - Then navigated to payload.webUrl (WhatsApp Web URL with TEXT only) ✗
 *   - The PDF was never shared — only a text message appeared
 *
 * AFTER (fixed):
 *   - Calls downloadReceiptAsPDF() ✓
 *   - Then navigates to payload.fitshareUrl (fitshare://send?phone=...&file=...) ✓
 *   - Windows resolves fitshare:// → PowerShell script
 *   - PowerShell finds the downloaded PDF, copies it to clipboard,
 *     focuses WhatsApp Web, finds the contact by phone, pastes & sends
 *   - Result: The exact SAME PDF as "Download PDF" is shared via WhatsApp
 */
export async function triggerWhatsAppAutomation(
  payload: WhatsAppPayload,
  entry: BoxEntry,
  customer: Customer,
): Promise<void> {
  // Step 1: Download the PDF to the user's Downloads folder
  await downloadReceiptAsPDF(entry, customer);

  const url = payload.fitshareUrl;

  setTimeout(() => {
    window.location.href = url;
  }, 800);
}

export async function shareMobile(
  entry: BoxEntry,
  customer: Customer,
  overridePhone?: string,
): Promise<void> {
  await downloadReceiptAsPDF(entry, customer);
  const payload = await buildWhatsAppPayload(entry, customer, overridePhone);
  setTimeout(() => {
    window.location.href = payload.waMe;
  }, 600);
}

export async function shareReceiptViaWhatsApp(
  entry: BoxEntry,
  customer: Customer,
  overridePhone?: string,
): Promise<void> {
  const settings = await SettingsDB.get();
  if (settings && typeof settings.billPrefix === 'string') {
    cachedBillPrefix = settings.billPrefix;
  }
  const shareMethod = settings?.whatsappShareMethod || 'Direct WhatsApp Share';

  if (shareMethod === 'Direct WhatsApp Share') {
    const mobile = (overridePhone || customer.mobile || customer.alternateMobile || '').trim();
    if (!mobile) {
      throw new Error('No valid mobile number found for WhatsApp sharing.');
    }

    const base64Image = await downloadReceiptAsPDF(entry, customer, 'base64') as string;
    const fileName = receiptFilename(entry, customer, settings?.billPrefix);

    const res = await fetch('/api/whatsapp/send-direct', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        host: window.location.hostname,
        mobile,
        base64Image,
        fileName
      })
    });

    if (!res.ok) {
      const errData = await res.json().catch(() => ({}));
      throw new Error(errData.error || `Direct WhatsApp Share failed with status ${res.status}`);
    }
  } else {
    if (isMobileDevice()) {
      await shareMobile(entry, customer, overridePhone);
    } else {
      const payload = await buildWhatsAppPayload(entry, customer, overridePhone);
      await triggerWhatsAppAutomation(payload, entry, customer);
    }
  }
}
